// Copies the compiled circuits and contract ABIs into this package, so the
// app, relayer and scripts never read build folders directly. Re-run after
// `circuits/generate-verifiers.sh` or `forge build`.
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "../..");
const LIB = join(ROOT, "lib");

for (const circuit of ["spend", "redeem"]) {
  const c = JSON.parse(readFileSync(join(ROOT, "circuits/target", `${circuit}.json`), "utf8"));
  // noir_js needs only the ABI and bytecode; drop debug info to keep it small.
  const slim = { noir_version: c.noir_version, hash: c.hash, abi: c.abi, bytecode: c.bytecode, debug_symbols: "", file_map: {} };
  writeFileSync(join(LIB, "circuits", `${circuit}.json`), JSON.stringify(slim) + "\n");
  console.log(`circuits/${circuit}.json`);
}

const contracts = ["ShieldedPool", "Markets", "ResolverReceiver", "BatchSwapper"];
let out = "// GENERATED by scripts/sync-artifacts.mjs from contracts/out. Do not edit.\n";
for (const name of contracts) {
  // With two solc versions in the build (PoolManager pins 0.8.26), forge writes
  // Name.<version>.json and may leave an older Name.json behind: take the newest.
  const dir = join(ROOT, "contracts/out", `${name}.sol`);
  const file = readdirSync(dir)
    .filter((f) => f === `${name}.json` || (f.startsWith(`${name}.`) && f.endsWith(".json")))
    .map((f) => join(dir, f))
    .sort((x, y) => statSync(y).mtimeMs - statSync(x).mtimeMs)[0];
  const { abi } = JSON.parse(readFileSync(file, "utf8"));
  out += `\nexport const ${name[0].toLowerCase()}${name.slice(1)}Abi = ${JSON.stringify(abi, null, 2)} as const;\n`;
}
writeFileSync(join(LIB, "src/abi.ts"), out);
console.log("src/abi.ts");
